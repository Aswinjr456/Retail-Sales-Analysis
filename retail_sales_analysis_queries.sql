-- RETAIL SALES ANALYSIS PROJECT
-- Database: retail_sale_project
-- Tables: sales, customers, categories

USE retail_sale_project;

-- STEP 1: Create related lookup tables from the existing sales table.
-- These tables avoid re-entering data and keep the original sales table unchanged.

CREATE TABLE IF NOT EXISTS customers (
    customer_id INT PRIMARY KEY,
    gender VARCHAR(20),
    age INT
);

INSERT IGNORE INTO customers (customer_id, gender, age)
SELECT customer_id, MAX(gender), MAX(age)
FROM sales
GROUP BY customer_id;

CREATE TABLE IF NOT EXISTS categories (
    category VARCHAR(100) PRIMARY KEY
);

INSERT IGNORE INTO categories (category)
SELECT DISTINCT category
FROM sales;

-- STEP 2: Verify the three related tables.
SHOW TABLES;

-- QUESTION 1: What is the total revenue from all sales?
SELECT SUM(total_sale) AS total_revenue
FROM sales;

-- QUESTION 2: How many transactions took place?
SELECT COUNT(*) AS total_transactions
FROM sales;

-- QUESTION 3: How many unique customers made purchases?
SELECT COUNT(DISTINCT customer_id) AS unique_customers
FROM customers;

-- QUESTION 4: How many product categories are available?
SELECT COUNT(*) AS total_categories
FROM categories;

-- QUESTION 5: What is the total revenue generated by each category? 
SELECT c.category, SUM(s.total_sale) AS total_revenue
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category
ORDER BY total_revenue DESC;

-- QUESTION 6: What is the average sales amount per transaction?
SELECT AVG(total_sale) AS average_sale
FROM sales;

-- QUESTION 7: What is the total revenue generated by each gender? 
SELECT cu.gender, SUM(s.total_sale) AS total_revenue
FROM sales s
INNER JOIN customers cu ON s.customer_id = cu.customer_id
GROUP BY cu.gender
ORDER BY total_revenue DESC;

-- QUESTION 8: How many transactions occurred in each category? 
SELECT c.category, COUNT(*) AS transaction_count
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category
ORDER BY transaction_count DESC;

-- QUESTION 9: Who are the top 5 customers by total spending? 
SELECT cu.customer_id, cu.gender, cu.age,
       SUM(s.total_sale) AS total_spending
FROM sales s
INNER JOIN customers cu ON s.customer_id = cu.customer_id
GROUP BY cu.customer_id, cu.gender, cu.age
ORDER BY total_spending DESC
LIMIT 5;

-- QUESTION 10: What is the highest individual sale amount?
SELECT MAX(total_sale) AS highest_sale
FROM sales;

-- QUESTION 11: What is the total revenue for each month?
SELECT MONTH(sale_date) AS sale_month,
       MONTHNAME(sale_date) AS month_name,
       SUM(total_sale) AS monthly_revenue
FROM sales
GROUP BY MONTH(sale_date), MONTHNAME(sale_date)
ORDER BY sale_month;

-- QUESTION 12: What is the total profit (total sale minus COGS) by category? 
SELECT c.category,
       SUM(s.total_sale - s.cogs) AS total_profit
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category
ORDER BY total_profit DESC;

-- QUESTION 13: Which customers made more than 5 transactions? 
SELECT cu.customer_id, cu.gender, COUNT(*) AS transaction_count
FROM sales s
INNER JOIN customers cu ON s.customer_id = cu.customer_id
GROUP BY cu.customer_id, cu.gender
HAVING COUNT(*) > 5
ORDER BY transaction_count DESC;

-- QUESTION 14: What is the average spending per customer? 
SELECT AVG(customer_total) AS average_customer_spending
FROM (
    SELECT cu.customer_id, SUM(s.total_sale) AS customer_total
    FROM sales s
    INNER JOIN customers cu ON s.customer_id = cu.customer_id
    GROUP BY cu.customer_id
) AS customer_spending;

-- QUESTION 15: Which category has the highest quantity sold? 
SELECT c.category, SUM(s.quantiy) AS total_quantity
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category
ORDER BY total_quantity DESC
LIMIT 1;

-- QUESTION 16: Which customers spent more than the average customer spending? 
SELECT cu.customer_id, cu.gender,
       SUM(s.total_sale) AS total_spending
FROM sales s
INNER JOIN customers cu ON s.customer_id = cu.customer_id
GROUP BY cu.customer_id, cu.gender
HAVING SUM(s.total_sale) > (
    SELECT AVG(customer_total)
    FROM (
        SELECT SUM(total_sale) AS customer_total
        FROM sales
        GROUP BY customer_id
    ) AS customer_totals
)
ORDER BY total_spending DESC;

-- QUESTION 17: What is the second-highest distinct sale amount?
SELECT MAX(total_sale) AS second_highest_sale
FROM sales
WHERE total_sale < (SELECT MAX(total_sale) FROM sales);

-- QUESTION 18: Rank categories by total revenue.
SELECT c.category,
       SUM(s.total_sale) AS total_revenue,
       RANK() OVER (ORDER BY SUM(s.total_sale) DESC) AS revenue_rank
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category;

-- QUESTION 19: Who are the top 3 customers by number of transactions?
SELECT cu.customer_id, cu.gender,
       COUNT(*) AS transaction_count
FROM sales s
INNER JOIN customers cu ON s.customer_id = cu.customer_id
GROUP BY cu.customer_id, cu.gender
ORDER BY transaction_count DESC
LIMIT 3;

-- QUESTION 20: What percentage of total revenue comes from each category? 
SELECT c.category,
       SUM(s.total_sale) AS category_revenue,
       ROUND(
           SUM(s.total_sale) * 100.0 / (SELECT SUM(total_sale) FROM sales),
           2
       ) AS revenue_percentage
FROM sales s
INNER JOIN categories c ON s.category = c.category
GROUP BY c.category
ORDER BY revenue_percentage DESC;
